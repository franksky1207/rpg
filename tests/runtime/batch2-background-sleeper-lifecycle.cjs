"use strict";
const fs=require("node:fs"),vm=require("node:vm"),assert=require("node:assert/strict");
const listeners={document:{},window:{}};
let hidden=false,focused=true;
const document={get visibilityState(){return hidden?"hidden":"visible";},hasFocus(){return focused;},addEventListener(k,f){(listeners.document[k]??=[]).push(f);}};
const window={addEventListener(k,f){(listeners.window[k]??=[]).push(f);},requestAnimationFrame(fn){setTimeout(fn,1);}};
const ctx=vm.createContext({document,window,console,setTimeout,clearTimeout,Date,Set,Math,Number,Object,Promise});
vm.runInContext(fs.readFileSync("backgroundprogress.js","utf8"),ctx,{filename:"backgroundprogress.js"});
async function check(){
 assert.equal(window.CONTINUOUS_RUN_INFRA_INTEGRITY.passed,true);
 assert.equal(window.BACKGROUND_PROGRESS_FAST_CATCH_UP_POLICY_INTEGRITY.passed,true);
 window.backgroundProgressStart("main",{mode:"continuous"});
 let first=false,second=false;
 const a=window.backgroundProgressSleep(30,"main").then(()=>first=true);
 const b=window.backgroundProgressSleep(30,"main").then(()=>second=true);
 await new Promise(r=>setTimeout(r,40));
 assert.equal(first,true,"first overlapping wait must resolve");
 assert.equal(second,false,"second wait must be serialized, not simultaneous");
 await b;assert.equal(second,true);
 await a;
 window.backgroundProgressStart("main",{mode:"continuous"});
 const held=window.backgroundProgressSleep(90000,"main");
 let queued=false;
 const next=window.backgroundProgressSleep(90000,"main").then(()=>queued=true);
 assert.equal(window.backgroundProgressStop("main"),true);
 await Promise.all([held,next]);
 assert.equal(queued,true,"cancelled queued waiter must resolve without starting a new wait");
 assert.equal(window.backgroundProgressSnapshot(),null);
 window.backgroundProgressStart("main",{mode:"continuous"});
 const old=window.backgroundProgressSleep(90000,"main");
 const orphan=window.backgroundProgressSleep(90000,"main");
 window.backgroundProgressStart("void",{mode:"continuous"});
 await Promise.all([old,orphan]);
 assert.equal(window.backgroundProgressActiveKind(),"void");
 window.backgroundProgressStop("void");
 assert.equal((listeners.document.visibilitychange||[]).length,1);
 console.log("PASS overlapping sleep resolves in order; cancellation and owner replacement never retain orphan wait; integrity contracts pass");
}
check().catch(e=>{console.error(e);process.exitCode=1});
