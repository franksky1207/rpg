'use strict';
const assert=require('node:assert/strict'),vm=require('node:vm'),fs=require('node:fs');
const window={};window.window=window;
vm.runInNewContext(fs.readFileSync('3d-test/t3b-formal-assets.js','utf8'),{window});
const mapper=window.CivilizationFormalBAssets;
const doc=JSON.parse(fs.readFileSync('assets/3d/asset-registry.json','utf8'));
assert.equal(mapper.fixtureAllowed,false);
assert.equal(mapper.player(doc,'medium').ready,true);
assert.equal(mapper.player(doc,'nope').ready,false);
const sample=doc.assets.find(x=>x.type==='equipment'&&Array.isArray(x.names)&&x.names.length&&x.identity);
assert.ok(sample);
const query={name:sample.names[0],slot:sample.slot,world:sample.identity.world,chapter:sample.identity.chapter,area:sample.identity.area,level:sample.identity.minLevel,tier:sample.quality};
const good=mapper.equipment(doc,query);
assert.equal(good.ready,true);
const unlicensed=JSON.parse(JSON.stringify(doc));
const matching=unlicensed.assets.find(a=>a.id===good.asset.id);
matching.license='';
assert.equal(mapper.equipment(unlicensed,query).ready,false,'Unlicensed art must never be used formally');
const unlicensedPlayer=JSON.parse(JSON.stringify(doc));
unlicensedPlayer.assets.find(a=>a.id===doc.player.medium).license='';
assert.equal(mapper.player(unlicensedPlayer,'medium').ready,false,'Unlicensed player model must fail closed');
assert.equal(mapper.equipment(doc,{...query,name:'unmapped formal item'}).ready,false);
assert.equal(mapper.equipment(doc,{...query,world:3}).ready,false);
assert.equal(mapper.equipment(doc,{...query,slot:'not-a-slot'}).ready,false);
assert.equal(mapper.enemy(null,{id:'a',world:1,kind:'boss',location:'X',tier:'medium'}).ready,false);
assert.equal(mapper.enemy({schema:'civilization.formal.b.enemy-atlas.v1',publish:false,approved:true,entries:[]},{id:'a',world:1,kind:'boss',location:'X',tier:'medium'}).ready,false);
assert.equal(mapper.enemy({schema:'civilization.formal.b.enemy-atlas.v1',publish:true,approved:false,entries:[]},{id:'a',world:1,kind:'boss',location:'X',tier:'medium'}).ready,false);
console.log('PASS T3-B formal asset mapping: exact named five-slot registry, no GM fixture, enemy catalog fails closed');
