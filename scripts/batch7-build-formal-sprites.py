#!/usr/bin/env python3
"""Deterministic full-master alpha export. No generation, joint repair or gear layers.
Requires Pillow 11.3+ and numpy. Flood fill only neutral background connected to
explicit seeds; intact white armor is protected by its dark contour.
"""
from pathlib import Path
from collections import deque
import hashlib,json
import numpy as np
from PIL import Image,ImageFilter
ROOT=Path(__file__).resolve().parents[1]
SRC=ROOT/'development/combat-animation/batch7/approved-sources'
OUT=ROOT/'assets/era-player/v1'; OUT.mkdir(parents=True,exist_ok=True)
rows=[]
for epoch,file,seeds,threshold in [
 ('galaxy','galaxy_approved_master.png',[],0),
 ('universe','universe_approved_master.jpeg',[(0,0),(525,374)],230),
 ('higher','higher_complete_master_v2.png',[(0,0),(400,520),(500,1150)],208)]:
 raw=(SRC/file).read_bytes(); im=Image.open(SRC/file).convert('RGBA'); a=np.array(im); h,w=a.shape[:2]
 if seeds:
  rgb=a[:,:,:3].astype('int16'); neutral=(rgb.min(2)>=threshold)&((rgb.max(2)-rgb.min(2))<=26)
  removed=np.zeros((h,w),bool); q=deque()
  for x,y in seeds:
   assert neutral[y,x],(epoch,x,y)
   removed[y,x]=True;q.append((x,y))
  while q:
   x,y=q.popleft()
   for nx,ny in ((x-1,y),(x+1,y),(x,y-1),(x,y+1)):
    if 0<=nx<w and 0<=ny<h and neutral[ny,nx] and not removed[ny,nx]:
     removed[ny,nx]=True;q.append((nx,ny))
  # One-pixel antialias transition at the foreground contour, remove neutral
  # matte on that contour only. Saturated blade light stays part of the figure.
  mask=Image.fromarray((~removed).astype('uint8')*255)
  softened=np.array(mask.filter(ImageFilter.GaussianBlur(.45)))
  a[:,:,3]=np.minimum(a[:,:,3],softened)
 # Original galaxy alpha includes nearly invisible distant dust; discard <=8.
 a[:,:,3][a[:,:,3]<=8]=0
 im=Image.fromarray(a); bounds=im.getchannel('A').point(lambda v:255 if v>16 else 0).getbbox()
 # Normalize standing height and feet; retain the WHOLE silhouette, sword too.
 crop=im.crop(bounds); scale=min(430/crop.height,440/crop.width)
 size=(round(crop.width*scale),round(crop.height*scale));crop=crop.resize(size,Image.Resampling.LANCZOS)
 result=Image.new('RGBA',(512,512));result.alpha_composite(crop,(256-size[0]//2,461-size[1]))
 dest=OUT/f'era-{epoch}.webp';result.save(dest,'WEBP',lossless=True,method=6,exact=True)
 b=dest.read_bytes();alpha=np.array(result.getchannel('A')); ab=result.getchannel('A').point(lambda v:255 if v>16 else 0).getbbox()
 rows.append(dict(id=f'era-{epoch}',epoch=epoch,releaseKind='era-player-v1',version='1.0.0',status='complete',singleLayer=True,formalReleaseAllowed=True,formalBattleAllowed=True,gmPreviewAllowed=True,gmTestStatus='lightweight-accepted',facing='right-3/4',pivot=[.5,.9],source=dict(file=file,sha256=hashlib.sha256(raw).hexdigest()),asset=dict(path=dest.relative_to(ROOT).as_posix(),width=512,height=512,bytes=len(b),sha256=hashlib.sha256(b).hexdigest(),alphaBounds=list(ab)),export=dict(sourceBounds=list(bounds),neutralThreshold=threshold,backgroundSeeds=seeds,scale=scale,alphaZero=int((alpha==0).sum()),alphaOpaque=int((alpha>=250).sum()))))
manifest=dict(schema='cw.era-player-sprites.v1',version='20261018-lightweight1',license='User-provided approved masters; project derivative export only.',higherDesign=dict(version=2,cape=False,rings=False,floatingBodies=0),entries=rows)
(OUT/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
# The shared formal/GM import is metadata only; it never preloads bitmaps.
runtime=json.loads(json.dumps(manifest))
for row in runtime['entries']: row['source'].pop('file')
(ROOT/'3d-test/era-player-sprites.mjs').write_text('// Generated by scripts/batch7-build-formal-sprites.py. Metadata only.\nconst data='+json.dumps(runtime,ensure_ascii=False,separators=(',',':'))+';\nfunction freeze(x){if(x&&typeof x===\'object\'){Object.values(x).forEach(freeze);Object.freeze(x);}return x;}\nexport const release=freeze(data);\n')
print(json.dumps(rows,indent=2))
